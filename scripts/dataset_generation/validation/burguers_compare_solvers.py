# OVERALL SPACE-TIME ERROR METRICS
# ============================================================

def calculate_overall_errors(my_data, paper_data, output_dir):
    """
    Calculate solver-reference errors on the original PACMANN space-time grid.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    # Sort each dataset's coordinates.
    def sorted_data(dataset):
        x_order = np.argsort(dataset["x"])
        t_order = np.argsort(dataset["t"])

        x = dataset["x"][x_order]
        t = dataset["t"][t_order]
        U = dataset["U"][np.ix_(t_order, x_order)]

        return x, t, U

    x_my, t_my, U_my = sorted_data(my_data)
    x_paper, t_paper, U_paper = sorted_data(paper_data)

    # Select exact reference times without temporal interpolation.
    x_common, t_common = x_paper, t_paper
    indices = np.argmin(np.abs(t_my[:, None] - t_common[None, :]), axis=0)
    if not np.array_equal(t_my[indices], t_common):
        raise ValueError("The solver dataset lacks exact PACMANN snapshot times.")
    if x_paper.min() < x_my.min() or x_paper.max() > x_my.max():
        raise ValueError("The solver grid must cover the PACMANN spatial domain.")

    # Interpolate only the Chebyshev solution onto the unchanged reference grid.
    weights = (-1.0) ** np.arange(len(x_my))
    weights[[0, -1]] *= 0.5
    U_my_common = BarycentricInterpolator(
        x_my, U_my[indices], axis=1, wi=weights
    )(x_common)
    U_paper_common = U_paper
    n_t, n_x = U_paper_common.shape
    x_min, x_max = x_common.min(), x_common.max()
    t_min, t_max = t_common.min(), t_common.max()

    difference = U_my_common - U_paper_common
    abs_difference = np.abs(difference)

    # Global metrics over all space-time grid points.
    l2_error = np.linalg.norm(difference.ravel())
    reference_l2 = np.linalg.norm(U_paper_common.ravel())

    relative_l2 = l2_error / max(reference_l2, 1e-15)
    rms_error = np.sqrt(np.mean(difference**2))
    mean_absolute_error = np.mean(abs_difference)
    max_absolute_error = np.max(abs_difference)

    print("\n" + "=" * 55)
    print("OVERALL SPACE-TIME ERROR METRICS")
    print("=" * 55)
    print(f"Compared time range:       [{t_min:.6f}, {t_max:.6f}]")
    print(f"Compared spatial range:    [{x_min:.6f}, {x_max:.6f}]")
    print(f"Common grid:               {n_t} times x {n_x} positions")
    print(f"Global relative L2 error:  {relative_l2:.8e}")
    print(f"Global absolute L2 norm:   {l2_error:.8e}")
    print(f"Root mean square error:    {rms_error:.8e}")
    print(f"Mean absolute error:       {mean_absolute_error:.8e}")
    print(f"Maximum absolute error:    {max_absolute_error:.8e}")
    print("=" * 55)

    # Save metrics for later reference.
    metrics_file = output_dir / "overall_error_metrics.txt"

    with open(metrics_file, "w", encoding="utf-8") as f:
        f.write("Overall space-time error metrics\n")
        f.write(f"Time range: [{t_min}, {t_max}]\n")
        f.write(f"Spatial range: [{x_min}, {x_max}]\n")
        f.write(f"Common grid: {n_t} x {n_x}\n")
        f.write(f"Global relative L2 error: {relative_l2:.10e}\n")
        f.write(f"Global absolute L2 norm: {l2_error:.10e}\n")
        f.write(f"Root mean square error: {rms_error:.10e}\n")
        f.write(f"Mean absolute error: {mean_absolute_error:.10e}\n")
        f.write(f"Maximum absolute error: {max_absolute_error:.10e}\n")

    print(f"Metrics saved to: {metrics_file}")

    return {
        "relative_l2": relative_l2,
        "absolute_l2_norm": l2_error,
        "rms_error": rms_error,
        "mean_absolute_error": mean_absolute_error,
        "max_absolute_error": max_absolute_error,
    }



from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from scipy.interpolate import interp1d


# ============================================================
# CONFIGURATION
# ============================================================

MY_DATASET = Path("burgers_dataset/burgers_nu_0p0031830989_N512.npz")
PAPER_DATASET = Path("burgers_dataset/PACMANN_Burgers.npz")

# Target times to compare. Each dataset uses its nearest snapshot.
TARGET_TIMES = [0.0, 0.25, 0.50, 0.75, 1.0]

# Output directory for plots
OUTPUT_DIR = Path("burgers_comparison")


# ============================================================
# LOAD DATASETS
# ============================================================

def load_my_dataset(filename):
    """Load the dataset generated by the custom Burgers solver."""
    data = np.load(filename)

    x = np.asarray(data["x"], dtype=float).ravel()
    t = np.asarray(data["t"], dtype=float).ravel()
    U = np.asarray(data["U"], dtype=float)

    # Expected shape: (n_times, n_space)
    if U.shape != (len(t), len(x)):
        raise ValueError(
            f"Unexpected U shape in {filename}: {U.shape}. "
            f"Expected {(len(t), len(x))}."
        )

    nu = float(data["nu"]) if "nu" in data else None

    return {
        "name": "Solver",
        "x": x,
        "t": t,
        "U": U,
        "nu": nu,
    }


def load_paper_dataset(filename):
    """Load the Burgers.npz dataset used by the paper."""
    data = np.load(filename)

    x = np.asarray(data["x"], dtype=float).ravel()
    t = np.asarray(data["t"], dtype=float).ravel()
    usol = np.asarray(data["usol"], dtype=float)

    # The paper's reference code uses:
    # exact = data["usol"].T
    # Therefore, its expected usol shape is (n_space, n_times).
    if usol.shape == (len(x), len(t)):
        U = usol.T
    elif usol.shape == (len(t), len(x)):
        # Also support a dataset already stored as (n_times, n_space).
        U = usol
    else:
        raise ValueError(
            f"Unexpected usol shape in {filename}: {usol.shape}. "
            f"Expected {(len(x), len(t))} or {(len(t), len(x))}."
        )

    nu = float(data["nu"]) if "nu" in data else None

    return {
        "name": "PACMANN dataset",
        "x": x,
        "t": t,
        "U": U,
        "nu": nu,
    }


# ============================================================
# SELECT NEAREST SNAPSHOTS
# ============================================================

def nearest_snapshot(dataset, target_time):
    """Return the closest available snapshot and its actual time."""
    idx = int(np.argmin(np.abs(dataset["t"] - target_time)))

    return (
        float(dataset["t"][idx]),
        dataset["U"][idx],
    )


# ============================================================
# OVERLAID SOLUTION PLOTS
# ============================================================

def plot_solutions_overlay(my_data, paper_data, target_times, output_dir):
    """
    Plot both datasets on the same axes for each target time,
    using different colors and labels.

    Each dataset uses its nearest available snapshot. The actual
    snapshot times are included in the legend.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    fig, axes = plt.subplots(
        len(target_times),
        1,
        figsize=(10, 3.5 * len(target_times)),
        squeeze=False,
    )

    datasets = [
        (my_data, "tab:blue", "-"),
        (paper_data, "tab:orange", "--"),
    ]

    for i, target in enumerate(target_times):
        ax = axes[i, 0]

        for dataset, color, linestyle in datasets:
            actual_time, u = nearest_snapshot(dataset, target)

            # Sort x for consistent plotting because Chebyshev
            # nodes may be returned in descending order.
            order = np.argsort(dataset["x"])
            x_sorted = dataset["x"][order]
            u_sorted = u[order]

            ax.plot(
                x_sorted,
                u_sorted,
                color=color,
                linestyle=linestyle,
                linewidth=1.8,
                label=(
                    f'{dataset["name"]} '
                    f'(t = {actual_time:.6f})'
                ),
            )

        ax.set_title(f"Requested time: t = {target:.5f}")
        ax.set_xlabel("x")
        ax.set_ylabel("u(x, t)")
        ax.grid(True, linestyle=":")
        ax.legend()

    fig.suptitle(
        "1D viscous Burgers equation: solution comparison",
        fontsize=15,
    )
    fig.tight_layout()

    filename = output_dir / "solutions_overlay.png"
    fig.savefig(filename, dpi=200, bbox_inches="tight")
    print(f"Saved: {filename}")

    plt.show()


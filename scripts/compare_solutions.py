# SPACE-TIME HEATMAPS
# ============================================================

def plot_side_by_side(my_data, paper_data, output_dir):
    """
    Plot two space-time heatmaps side by side.

    Horizontal axis: time t
    Vertical axis: spatial position x
    Color: solution value u(x, t)
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    datasets = [my_data, paper_data]

    # Use the same color limits for both plots to allow
    # a meaningful visual comparison.
    global_min = min(np.min(d["U"]) for d in datasets)
    global_max = max(np.max(d["U"]) for d in datasets)

    fig, axes = plt.subplots(
        1, 2,
        figsize=(14, 5),
        sharey=True,
        constrained_layout=True,
    )

    for ax, dataset in zip(axes, datasets):
        x = dataset["x"]
        t = dataset["t"]
        U = dataset["U"]  # Expected shape: (n_times, n_space)

        # Sort coordinates for consistent plotting.
        x_order = np.argsort(x)
        t_order = np.argsort(t)

        x_sorted = x[x_order]
        t_sorted = t[t_order]
        U_sorted = U[np.ix_(t_order, x_order)]

        # U has shape (n_times, n_space), so transpose it
        # to match horizontal=time and vertical=position.
        mesh = ax.pcolormesh(
            t_sorted,
            x_sorted,
            U_sorted.T,
            shading="auto",
            cmap="RdBu_r",
            vmin=global_min,
            vmax=global_max,
        )

        ax.set_title(dataset["name"])
        ax.set_xlabel("Time, t")
        ax.set_ylabel("Position, x")
        ax.set_xlim(t_sorted.min(), t_sorted.max())
        ax.set_ylim(x_sorted.min(), x_sorted.max())

        colorbar = fig.colorbar(mesh, ax=ax)
        colorbar.set_label("u(x, t)")

    fig.suptitle("1D viscous Burgers equation: space-time solutions")

    filename = output_dir / "space_time_heatmaps.png"
    fig.savefig(filename, dpi=200, bbox_inches="tight")
    print(f"Saved: {filename}")

    plt.show()

